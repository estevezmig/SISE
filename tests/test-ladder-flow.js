const assert = require('node:assert/strict');
const fs = require('node:fs');
const conv = require('../converter-core.js');
const flow = require('../integration/ladder-flow.js');
const load = name => conv.classify(JSON.parse(fs.readFileSync(`${__dirname}/../${name}.grafcet.json`)));
const model = load('ejemplo_secuencia');
const a = flow.evaluate(model, {Start:true, Stop:false, Motor:false}, ['s_0'], true);
assert.equal(a.values.T1,true); assert.equal(a.values.T2,false);
assert.equal(a.values['X0⁺'],false); assert.equal(a.values['X1⁺'],true);
assert.equal(a.rungs[0].branches[0].contacts[2].closed,true);
assert.equal(a.rungs[0].branches[0].power,true);
const b = flow.evaluate(model, {Start:false,Stop:false,Motor:false}, ['s_1'], true);
assert.equal(b.values.Motor,true); assert.equal(b.values['X1⁺'],true);
const c = flow.evaluate(model, {Start:true, Stop:true, Motor:false}, ['s_0'], true);
assert.equal(c.values.T1,false); assert.equal(c.rungs[0].branches[0].contacts[2].closed,false);
assert.equal(c.rungs[0].branches[0].contacts[2].after,false);
const off=flow.evaluate(model,{Start:true,Stop:false,Motor:false},['s_0'],false);
assert.ok(off.rungs.every(r=>!r.result));
assert.throws(()=>flow.assertSupported(load('ejemplo_semaforo')),/Flancos/);
assert.match(flow.render(a),/#4fff98/);
console.log('OK: flujo booleano, contactos negados, transiciones, salidas y restricciones');
