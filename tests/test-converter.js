const assert=require('node:assert/strict');
const fs=require('node:fs');
const conv=require('../converter-core.js');
const load=s=>JSON.parse(fs.readFileSync(__dirname+'/../'+s+'.grafcet.json','utf8'));
const a=conv.classify(load('ejemplo_secuencia'));
assert.equal(a.steps.length,2);assert.equal(a.transitions.length,2);assert.equal(a.actions[0].name,'Motor');
assert.match(conv.generateLogic(a),/Motor := X1/);
assert.match(conv.svgLadder(a),/<svg/);assert.match(conv.svgFup(a),/FUP/);
assert.equal(conv.dnf(conv.parseExpr('Start + Stop',['Start','Stop'])).length,2);
assert.equal(conv.dnf(conv.parseExpr('/(Start + Stop)',['Start','Stop']))[0].length,2);
const light=conv.classify(load('ejemplo_semaforo'));
assert.equal(light.steps.length,3);assert.equal(light.transitions.length,3);
assert.equal(light.storedActions.length,2);assert.equal(light.helpers.filter(h=>h.kind==='timer').length,4);
assert.ok(light.helpers.some(h=>h.name==='TON_X0_10000ms.Q'));
assert.ok(light.helpers.some(h=>h.name==='R_TRIG_request.Q'));
assert.equal(light.transitions[1].branches.length,2);
assert.match(conv.generateLogic(light),/Req := 1/);
assert.match(conv.svgLadder(light),/TON_X1_30000ms/);
const drill=conv.classify(load('ejemplo_taladrado'));
assert.equal(drill.steps.length,6);assert.equal(drill.transitions.length,7);
assert.equal(drill.outgoing.X4.length,2);assert.equal(drill.incoming.X0.length,2);
assert.ok(drill.helpers.some(h=>h.name==='CMP_Count_GE_100.Q'));
assert.ok(drill.helpers.some(h=>h.name==='R_TRIG_start.Q'));
assert.ok(drill.storedActions.some(a=>a.target==='Count'&&a.op==='ADD'));
assert.ok(drill.storedActions.some(a=>a.target==='Count'&&a.op==='MOVE'));
assert.ok(drill.storedActions.some(a=>a.target==='Clamp'&&a.op==='MOVE'));
assert.match(conv.generateLogic(drill),/X0_next :=/);
assert.match(conv.svgLadder(drill),/CMP_Count_LT_100/);
assert.match(conv.svgFup(drill),/FUP/);
const parallel=conv.classify(load('ejemplo_paralelo'));
assert.deepEqual(parallel.transitions[0].to,['X1','X2']);
assert.deepEqual(parallel.transitions[3].from,['X3','X4']);
assert.equal(parallel.incoming.X1[0],parallel.incoming.X2[0]);
assert.ok(parallel.helpers.some(h=>h.ms===2000));
assert.throws(()=>conv.classify({...load('ejemplo_secuencia'),schemaVersion:5}),/formato GrafcetMaker v4/i);
assert.throws(()=>conv.parseExpr('99s/X9',[{name:'Start',type:'BOOL'}],[{number:0}]),/etapa no existente/i);
const unsupported=load('ejemplo_taladrado');unsupported.grafcets.g1.actions.a1.kind='forcing';
assert.throws(()=>conv.classify(unsupported),/todavía no compatible/i);
const bad=load('ejemplo_taladrado');bad.grafcets.g1.transitions.t1.receptivity='12s/X0 + (Count >=';
assert.throws(()=>conv.classify(bad),/incomplet[ao]|Token inesperado|no admitido/i);
console.log('OK: 33+ comprobaciones sobre secuencias, semáforo, taladrado y paralelo');