const assert = require('node:assert/strict');
const fs = require('node:fs');
const cp = require('../converter-core.js');
const file = JSON.parse(fs.readFileSync(__dirname+'/../ejemplo_secuencia.grafcet.json','utf8'));
const model=cp.classify(file);
assert.equal(model.steps.length,2);
assert.equal(model.transitions.length,2);
assert.equal(model.actions[0].name,'Motor');
assert.equal(model.transitions[0].branches.length,1);
assert.deepEqual(model.transitions[0].branches[0],[{name:'X0',neg:false},{name:'Start',neg:false},{name:'Stop',neg:true}]);
assert.match(cp.generateLogic(model),/T1 := X0 AND Start AND NOT Stop/);
assert.match(cp.generateLogic(model),/Motor := X1/);
assert.match(cp.svgLadder(model),/<svg/);
assert.match(cp.svgFup(model),/FUP/);
const clone=(obj)=>structuredClone(obj);
let bad=clone(file);bad.grafcets.g_main.transitions.t_start.from.push('s_1');assert.throws(()=>cp.classify(bad),/divergencias|convergencias/i);
bad=clone(file);bad.grafcets.g_main.transitions.t_start.receptivity='RE Start';assert.throws(()=>cp.classify(bad),/todavía no se convierten/i);
bad=clone(file);bad.schemaVersion=5;assert.throws(()=>cp.classify(bad),/formato GrafcetMaker v4/);
assert.equal(cp.dnf(cp.parseExpr('Start + Stop',['Start','Stop'])).length,2);
assert.equal(cp.dnf(cp.parseExpr('/(Start + Stop)',['Start','Stop']))[0].length,2);
console.log('OK: 14 verificaciones sobre el conversor genérico de SISE');